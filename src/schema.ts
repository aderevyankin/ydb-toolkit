import {mkdir, writeFile} from "node:fs/promises";
import path from "node:path";
import {Type_PrimitiveTypeId as P, type Type} from "@ydbjs/api/value";
import type {MigrationDb, TableRegistry} from "./migrations.js";

const primitiveTypes: Partial<Record<P, string>> = {
  [P.UTF8]: "string", [P.STRING]: "globalThis.Uint8Array", [P.JSON]: "unknown", [P.JSON_DOCUMENT]: "unknown",
  [P.TIMESTAMP]: "globalThis.Date", [P.DATE]: "globalThis.Date", [P.DATETIME]: "globalThis.Date", [P.BOOL]: "boolean",
  [P.INT8]: "number", [P.INT16]: "number", [P.INT32]: "number", [P.INT64]: "bigint",
  [P.UINT8]: "number", [P.UINT16]: "number", [P.UINT32]: "number", [P.UINT64]: "bigint",
  [P.FLOAT]: "number", [P.DOUBLE]: "number",
};

export function typescriptType(type?: Type): string {
  const value = type?.type;
  if (!value) {return "unknown";}
  if (value.case === "typeId") {return primitiveTypes[value.value] ?? "unknown";}
  if (value.case === "optionalType") {return `(${typescriptType(value.value.item)}) | null`;}
  if (value.case === "listType") {return `(${typescriptType(value.value.item)})[]`;}
  if (value.case === "structType") {
    return `{ ${value.value.members.map(member => `${JSON.stringify(member.name)}: ${typescriptType(member.type)}`).join("; ")} }`;
  }
  if (value.case === "tupleType") {return `[${value.value.elements.map(typescriptType).join(", ")}]`;}
  return "unknown";
}

function migrationType(type?: Type): string {
  const value = type?.type;
  if (value?.case === "optionalType") {return `OPTIONAL_${migrationType(value.value.item)}`;}
  return value?.case === "typeId" ? P[value.value] : "UNKNOWN_STRUCTURE";
}

export async function generateTypes(db: MigrationDb, options: {out: string; registry?: string}): Promise<void> {
  if (options.registry && path.resolve(options.out) === path.resolve(options.registry)) {throw new Error("Types and registry outputs must differ");}
  const tables = await db.listTables();
  const tableColumns: TableRegistry = Object.create(null);
  const names = new Set<string>();
  let output = "// Generated by ydb-toolkit. Do not edit.\n";
  for (const table of tables) {
    let name = table.split(/[^A-Za-z0-9]+/).filter(Boolean).map(part => part.charAt(0).toUpperCase() + part.slice(1)).join("");
    if (!/^[A-Za-z_]/.test(name)) {name = `Table${name}`;}
    if (names.has(name)) {throw new Error(`Generated interface name collision: ${name}`);}
    names.add(name);
    const {columns} = await db.describeTable(table);
    output += `\nexport interface ${name} {\n${columns.map(column => `  ${JSON.stringify(column.name)}: ${typescriptType(column.type)};`).join("\n")}\n}\n`;
    tableColumns[table] = Object.fromEntries(columns.map(column => [column.name, migrationType(column.type)]));
  }
  await mkdir(path.dirname(path.resolve(options.out)), {recursive: true});
  await writeFile(options.out, output, "utf8");
  if (options.registry) {
    await mkdir(path.dirname(path.resolve(options.registry)), {recursive: true});
    const existing = Object.fromEntries(tables.map(table => [table.toUpperCase(), table]));
    if (Object.keys(existing).length !== tables.length) {throw new Error("Uppercase table registry key collision");}
    await writeFile(options.registry, `// Generated by ydb-toolkit. Do not edit.\nexport const TableColumns = JSON.parse(${JSON.stringify(JSON.stringify(tableColumns))});\nexport const ExistingTables = JSON.parse(${JSON.stringify(JSON.stringify(existing))});\n`, "utf8");
  }
}
